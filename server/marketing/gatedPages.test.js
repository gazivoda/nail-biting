import { describe, it, expect } from 'vitest';
import { createFlags } from '../features.js';
import {
  GATED_LINKS_ID, gatedFlagOf, gatedFooterLinks, gatedLinkLabel, gatedLinksArticleHtml, gatedLinksMarkerTag, gatedLlmsFullText,
  gatedLlmsTxtLines, gatedNavLinks, gatedOgFile, gatedSitemapEntries, isClosedGatedFile, isGateOpen,
  jsonForScript, openGatedPages, pageDataPath, pathOfPageData, resolveGatedPage, withGatedLlmsFull, withGatedLlmsTxt, withGatedSitemapEntries,
  withoutClosedPageLinks,
} from './gatedPages.js';

const quiet = () => {};
const SITEMAP = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<!-- Generated by scripts/sync-seo.mjs — do not edit by hand. -->',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  '',
  '  <url>',
  '    <loc>https://stopbiting.today/</loc>',
  '    <lastmod>2026-10-21</lastmod>',
  '    <changefreq>weekly</changefreq>',
  '    <priority>1.0</priority>',
  '  </url>',
  '',
  '</urlset>',
  '',
].join('\n');

describe('isGateOpen', () => {
  const off = createFlags({}, { warn: quiet });
  const on = createFlags({ FEATURE_FLAGS: 'compare_competitors' }, { warn: quiet });

  it('serves an entry with no flag whatever the flags are', () => {
    expect(isGateOpen(off, { title: 'x' })).toBe(true);
    expect(isGateOpen(off, undefined)).toBe(true);
  });

  it('serves a flagged entry only while its flag is on', () => {
    const meta = { title: 'x', flag: 'compare_competitors' };
    expect(isGateOpen(off, meta)).toBe(false);
    expect(isGateOpen(on, meta)).toBe(true);
  });

  it('an unrelated flag does not open it', () => {
    const other = createFlags({ FEATURE_FLAGS: 'social_proof' }, { warn: quiet });
    expect(isGateOpen(other, { flag: 'compare_competitors' })).toBe(false);
  });
});

describe('gatedNavLinks', () => {
  it('lists [href, title] in file order, and nothing for no content', () => {
    const content = { '/compare/a': { title: 'A' }, '/compare/b': { title: 'B' } };
    expect(gatedNavLinks(content)).toEqual([['/compare/a', 'A'], ['/compare/b', 'B']]);
    expect(gatedNavLinks({})).toEqual([]);
    expect(gatedNavLinks(undefined)).toEqual([]);
  });
});

describe('gatedSitemapEntries and withGatedSitemapEntries', () => {
  const content = { '/compare/hands-off': {}, '/compare/habitaware-keen': {} };

  it('uses the freshness ledger date and never invents one', () => {
    const warnings = [];
    const entries = gatedSitemapEntries(
      content,
      path => (path === '/compare/hands-off' ? '2026-10-23' : null),
      { warn: m => warnings.push(m) },
    );
    expect(entries).toEqual([
      { loc: 'https://stopbiting.today/compare/hands-off', lastmod: '2026-10-23', changefreq: 'monthly', priority: '0.8' },
    ]);
    expect(warnings).toHaveLength(1);
    expect(warnings[0]).toMatch(/habitaware-keen/);
  });

  it('splices the entries in before </urlset> in the shape sync-seo writes', () => {
    const entries = gatedSitemapEntries(content, () => '2026-10-23');
    const out = withGatedSitemapEntries(SITEMAP, entries);
    expect(out).toContain('<loc>https://stopbiting.today/compare/hands-off</loc>');
    expect(out).toContain('<loc>https://stopbiting.today/compare/habitaware-keen</loc>');
    expect(out.endsWith('  </url>\n\n</urlset>\n')).toBe(true);
    // Everything that was there is still there, untouched and in order.
    expect(out.startsWith(SITEMAP.slice(0, SITEMAP.lastIndexOf('</urlset>')))).toBe(true);
    // One <url> per page, the original included.
    expect(out.match(/<url>/g)).toHaveLength(3);
  });

  it('returns the sitemap unchanged when there is nothing to add', () => {
    expect(withGatedSitemapEntries(SITEMAP, [])).toBe(SITEMAP);
  });
});

describe('per-page flags (WS11b)', () => {
  const pages = {
    '/compare/hands-off': { title: 'Hands Off' },
    '/features/phone-companion': { title: 'Phone' },
    '/features/share-with-therapist': { title: 'Share' },
  };
  const flagsOf = {
    '/compare/hands-off': 'compare_competitors',
    '/features/phone-companion': 'phone_companion',
    '/features/share-with-therapist': 'share_links',
  };
  const flagSet = names => createFlags({ FEATURE_FLAGS: names }, { warn: quiet });

  it('opens a page only with its own flag: another page\'s flag opens nothing', () => {
    expect(Object.keys(openGatedPages(pages, flagsOf, flagSet('')))).toEqual([]);
    expect(Object.keys(openGatedPages(pages, flagsOf, flagSet('phone_companion')))).toEqual(['/features/phone-companion']);
    expect(Object.keys(openGatedPages(pages, flagsOf, flagSet('compare_competitors')))).toEqual(['/compare/hands-off']);
    expect(Object.keys(openGatedPages(pages, flagsOf, flagSet('hrt_coaching,referrals')))).toEqual([]);
    expect(Object.keys(openGatedPages(pages, flagsOf, flagSet('share_links,phone_companion')))).toEqual(
      ['/features/phone-companion', '/features/share-with-therapist'],
    );
  });

  it('a page the build did not give a flag falls back to the competitor flag it always had', () => {
    expect(gatedFlagOf({}, '/compare/hands-off')).toBe('compare_competitors');
    expect(gatedFlagOf(undefined, '/compare/hands-off')).toBe('compare_competitors');
    expect(Object.keys(openGatedPages({ '/compare/hands-off': {} }, {}, flagSet('compare_competitors')))).toEqual(['/compare/hands-off']);
    expect(Object.keys(openGatedPages({ '/compare/hands-off': {} }, {}, flagSet('phone_companion')))).toEqual([]);
  });

  it('resolves markers, copy rules and placeholders, and drops a section a marker emptied', () => {
    const page = {
      title: 'T',
      intro: 'You both get {{REFERRAL_CREDIT}}.',
      sections: [
        { heading: 'Always', body: '{{if event_sync}}Synced.{{else}}Local.{{end}}' },
        { heading: '{{if urge_timer}}Timer{{end}}', body: '{{if urge_timer}}About it.{{end}}' },
      ],
    };
    const off = resolveGatedPage(page, { isOn: () => false, tokens: { REFERRAL_CREDIT: 'one month' } });
    expect(off).toEqual({ title: 'T', intro: 'You both get one month.', sections: [{ heading: 'Always', body: 'Local.' }] });
    const on = resolveGatedPage(page, { isOn: name => name === 'event_sync' || name === 'urge_timer', tokens: { REFERRAL_CREDIT: '30 days' } });
    expect(on.sections).toEqual([{ heading: 'Always', body: 'Synced.' }, { heading: 'Timer', body: 'About it.' }]);
    expect(JSON.stringify(on)).not.toMatch(/\{\{/);
  });
});

describe('llms files and cards for open pages', () => {
  const open = { '/features/phone-companion': { title: 'Phone companion' } };
  const llmsFull = { '/features/phone-companion': '## Phone companion\nURL: https://stopbiting.today/features/phone-companion\n' };

  it('adds the open pages\' blocks to llms-full.txt and nothing when none is open', () => {
    const addition = gatedLlmsFullText(open, llmsFull);
    expect(addition).toContain('URL: https://stopbiting.today/features/phone-companion');
    expect(withGatedLlmsFull('# base\n', addition)).toBe(`# base\n\n${addition}`);
    expect(gatedLlmsFullText({}, llmsFull)).toBe('');
    expect(withGatedLlmsFull('# base\n', '')).toBe('# base\n');
    expect(gatedLlmsFullText(open, llmsFull, t => t.toUpperCase())).toContain('PHONE COMPANION');
  });

  it('adds one line per open page to llms.txt, with the description, and nothing when none is open', () => {
    const lines = gatedLlmsTxtLines(open, path => ({ description: `About ${path}` }));
    expect(lines).toEqual(['- [Phone companion](https://stopbiting.today/features/phone-companion): About /features/phone-companion']);
    expect(withGatedLlmsTxt('# Stop Biting\n', lines)).toBe(`# Stop Biting\n\n## Features and newer pages\n\n${lines[0]}\n`);
    expect(withGatedLlmsTxt('# Stop Biting\n', [])).toBe('# Stop Biting\n');
    expect(gatedLlmsTxtLines(open, () => undefined)).toEqual([]);
  });

  it('knows which /og card belongs to a closed page', () => {
    const flagsOf = { '/features/desktop-app': 'desktop_app', '/solutions/cuticle-biting': 'detection_behaviors' };
    expect(gatedOgFile('/features/desktop-app')).toBe('features-desktop-app.png');
    const off = createFlags({}, { warn: quiet });
    const on = createFlags({ FEATURE_FLAGS: 'desktop_app' }, { warn: quiet });
    expect(isClosedGatedFile('features-desktop-app.png', flagsOf, off)).toBe(true);
    expect(isClosedGatedFile('features-desktop-app.png', flagsOf, on)).toBe(false);
    expect(isClosedGatedFile('solutions-cuticle-biting.png', flagsOf, on)).toBe(true);
    expect(isClosedGatedFile('site.png', flagsOf, off)).toBe(false);
    expect(isClosedGatedFile('compare-stop-biting-vs-hands-off.png', flagsOf, off)).toBe(false);
  });

  it('maps a page to its data file and back, and refuses anything else', () => {
    expect(pageDataPath('/features/phone-companion')).toBe('/page-data/features/phone-companion.json');
    expect(pathOfPageData('/page-data/features/phone-companion.json')).toBe('/features/phone-companion');
    expect(pathOfPageData('/page-data/solutions/cuticle-biting.json')).toBe('/solutions/cuticle-biting');
    expect(pathOfPageData('/page-data/../server.js')).toBeNull();
    expect(pathOfPageData('/page-data/features/x.txt')).toBeNull();
    expect(pathOfPageData('/features/x.json')).toBeNull();
  });

  it('writes JSON that cannot end a script block early', () => {
    const text = jsonForScript({ a: '</script><!--', b: String.fromCharCode(0x2028) });
    expect(text).not.toContain('</script>');
    expect(text).not.toContain('<!--');
    expect(text).not.toContain(String.fromCharCode(0x2028));
    expect(JSON.parse(text)).toEqual({ a: '</script><!--', b: String.fromCharCode(0x2028) });
  });
});

describe('links to the open pages: footer, marker and crawler article', () => {
  const open = {
    '/features/phone-companion': { title: 'Log nail biting from your phone in two taps' },
    '/features/referral-program': { title: 'Refer a friend: you both get bonus access' },
    '/solutions/cuticle-biting': { title: 'Cuticle and skin biting: the same mouth alarm, logged under its own name' },
  };
  const escape = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

  it('is one [href, label] per open page, in file order, and nothing when none is open', () => {
    expect(gatedFooterLinks(open)).toEqual([
      ['/features/phone-companion', 'Log nail biting from your phone in two taps'],
      ['/features/referral-program', 'Refer a friend'],
      ['/solutions/cuticle-biting', 'Cuticle and skin biting'],
    ]);
    expect(gatedFooterLinks({})).toEqual([]);
    expect(gatedFooterLinks(undefined)).toEqual([]);
    expect(gatedFooterLinks({ '/features/x': {} })).toEqual([]);
  });

  it('labels a page with its title up to the first colon, and with the whole title when that leaves nothing', () => {
    expect(gatedLinkLabel('Refer a friend: you both get bonus access')).toBe('Refer a friend');
    expect(gatedLinkLabel('No colon in this one')).toBe('No colon in this one');
    expect(gatedLinkLabel(': starts with one')).toBe(': starts with one');
    expect(gatedLinkLabel(undefined)).toBe('');
  });

  it('writes a data block the footer reads, and adds nothing at all when there is no link', () => {
    const links = gatedFooterLinks(open);
    const tag = gatedLinksMarkerTag(links);
    expect(tag.startsWith(`<script type="application/json" id="${GATED_LINKS_ID}">`)).toBe(true);
    expect(JSON.parse(tag.replace(/^<script[^>]*>/, '').replace(/<\/script>$/, ''))).toEqual(links);
    expect(gatedLinksMarkerTag([])).toBe('');
    // text that looks like the end of the block cannot end it
    expect(gatedLinksMarkerTag([['/features/a', 'x </script><!--']]).match(/<\/script>/g)).toHaveLength(1);
  });

  it('lists the same links as real anchors for readers that do not run the page, with the text escaped', () => {
    const html = gatedLinksArticleHtml(gatedFooterLinks(open), escape);
    expect(html.startsWith('<nav aria-label="')).toBe(true);
    expect(html).toContain('<a href="/features/phone-companion">Log nail biting from your phone in two taps</a>');
    expect(html).toContain('<a href="/features/referral-program">Refer a friend</a>');
    expect(html.match(/<a /g)).toHaveLength(3);
    expect(gatedLinksArticleHtml([], escape)).toBe('');
    expect(gatedLinksArticleHtml([['/features/a', 'R&D "x" <b>']], escape)).toContain('R&amp;D &quot;x&quot; &lt;b&gt;');
  });
});

describe('withoutClosedPageLinks', () => {
  const flagsOf = { '/features/habit-reversal-coaching': 'hrt_coaching', '/features/phone-companion': 'phone_companion' };
  const page = {
    title: 'Phone',
    relatedPosts: [
      { href: '/how-it-works', label: 'How it works' },
      { href: '/features/habit-reversal-coaching', label: 'Coaching after the alarm' },
      { href: '/pricing', label: 'Pricing' },
    ],
  };
  const flagSet = names => createFlags({ FEATURE_FLAGS: names }, { warn: quiet });

  it('drops the links to gated pages whose flag is off, and keeps every other link in its place', () => {
    const out = withoutClosedPageLinks(page, flagsOf, flagSet('phone_companion'));
    expect(out.relatedPosts.map(p => p.href)).toEqual(['/how-it-works', '/pricing']);
    expect(out.title).toBe('Phone');
  });

  it('keeps a link to a gated page while that page\'s own flag is on, and hands back the same page when nothing goes', () => {
    const out = withoutClosedPageLinks(page, flagsOf, flagSet('phone_companion,hrt_coaching'));
    expect(out).toBe(page);
    expect(withoutClosedPageLinks({ title: 'x' }, flagsOf, flagSet(''))).toEqual({ title: 'x' });
    expect(withoutClosedPageLinks(page, undefined, flagSet(''))).toBe(page);
  });
});
