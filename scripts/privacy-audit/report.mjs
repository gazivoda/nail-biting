#!/usr/bin/env node
// Turns the JSON files the audit wrote (docs/agents/privacy-audit-results/*.json) into the "Results" section of
// docs/agents/privacy-audit-report.md, between the markers <!-- results:start --> and <!-- results:end -->, so the
// numbers in the report are never typed by hand. Re-run after every audit:
//   node scripts/privacy-audit/report.mjs [--dir DIR] [--report FILE]
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const argv = process.argv.slice(2);
const opt = (name, fallback) => { const i = argv.indexOf(name); return i === -1 ? fallback : argv[i + 1]; };
const dir = opt('--dir', join(REPO, 'docs', 'agents', 'privacy-audit-results'));
const reportFile = opt('--report', join(REPO, 'docs', 'agents', 'privacy-audit-report.md'));

const order = ['canary', 'flagsoff', 'off', 'on', 'flagsoff-probe', 'off-probe', 'on-probe'];
const files = readdirSync(dir).filter(f => f.endsWith('.json') && f !== 'summary.json').map(f => f.replace(/\.json$/, '')).sort((a, b) => order.indexOf(a) - order.indexOf(b));
const R = Object.fromEntries(files.map(f => [f, JSON.parse(readFileSync(join(dir, `${f}.json`), 'utf8'))]));
const label = {
  flagsoff: 'flags off (production as shipped)', off: 'sync OFF (event_sync flag on, nobody opted in)', on: 'sync ON (opted in through the UI)',
  'flagsoff-probe': 'flags off, probe build', 'off-probe': 'sync OFF, probe build (real alarms)', 'on-probe': 'sync ON, probe build (real alarms)', canary: 'canary (deliberate leaks)',
};
const hostList = (h) => Object.entries(h ?? {}).map(([k, v]) => `\`${k}\` (${v})`).join(', ');
const first = Object.values(R).find(r => r.startedAt);

const out = [];
out.push(`_Generated by \`node scripts/privacy-audit/report.mjs\` from \`docs/agents/privacy-audit-results/*.json\`. Run: ${first?.startedAt?.slice(0, 16).replace('T', ' ')} UTC, ${first?.chrome ?? 'Chrome'}, Node ${process.version}, ${first?.seconds ?? '?'} s of detection per mode._`);
out.push('');
out.push('| Mode | Verdict | Detection | Logged through the UI | Requests (http / ws frames) | `/api/events/*` | Hosts contacted | Violations |');
out.push('|---|---|---|---|---|---|---|---|');
for (const [mode, r] of Object.entries(R)) {
  if (mode === 'canary') continue;
  const s = r.stats; const sc = r.scenario ?? {};
  const logged = `${sc.bitesLogged ?? 0} bites, ${sc.urgeLogged ?? 0} urge${r.probe ? `, ${sc.alarmsRaised ?? 0} real alarms` : ''}, ${sc.photo?.length ?? 0} diary photo`;
  out.push(`| ${label[mode] ?? mode} | **${r.verdict}** | ${sc.durationSec ?? '?'} s, ${r.detectionFramesPerSecond} video frames/s to MediaPipe | ${logged} | ${s?.requests ?? '?'} / ${s?.webSocketFrames ?? 0} | ${s?.eventsRequests ?? 0} (${s?.syncPosts ?? 0} sync POSTs, ${s?.syncEvents ?? 0} event records) | ${hostList(s?.hosts)} | ${r.violations ?? 0} |`);
}
out.push('');
for (const [mode, r] of Object.entries(R)) {
  if (mode === 'canary') continue;
  const s = r.stats; const sc = r.scenario ?? {};
  out.push(`### ${label[mode] ?? mode}`);
  out.push('');
  out.push(`- Verdict **${r.verdict}**; ${r.violations ?? 0} violations; ${(r.findings ?? []).filter(f => f.severity === 'warn').length} notes.`);
  out.push(`- Flags on the server: \`${r.flags || '(none)'}\`. Signed in with a real session (GET /api/user/me answered 200).`);
  out.push(`- Detection ran for ${sc.durationSec} s and handed ${sc.finalFrames} video frames to MediaPipe (${r.detectionFramesPerSecond} a second)${(sc.photo?.length ?? 0) ? ', and kept doing so through the diary photo session (a second camera stream)' : ''}.`);
  out.push(`- Requests recorded: ${s?.requests} HTTP (${Object.entries(s?.byTarget ?? {}).map(([k, v]) => `${k}: ${v}`).join(', ')} records by context), ${s?.hookCalls} in-page hook reports, ${s?.webSocketFrames} WebSocket frames. Bodies inspected: ${s?.bodiesChecked} (${s?.bytesChecked} bytes), unreadable: ${s?.bodiesUnreadable}.`);
  out.push(`- Resource types: ${Object.entries(s?.byResourceType ?? {}).map(([k, v]) => `${k} ${v}`).join(', ')}.`);
  out.push(`- Hosts: ${hostList(s?.hosts)}.`);
  out.push(`- \`/api/events/*\` requests: **${s?.eventsRequests}**${mode.startsWith('on') ? `; sync POST bodies: top-level keys seen \`${(s?.topKeysSeen ?? []).join(', ')}\`; event keys seen \`${(s?.eventKeysSeen ?? []).join(', ')}\`; competingResponse keys \`${(s?.responseKeysSeen ?? []).join(', ') || '-'}\`; ${r.distinctEventIdsSynced} distinct events synced` : ' (required to be zero)'}.`);
  if (mode.startsWith('on')) {
    const w = r.whitelist ?? {};
    const unseen = (w.event ?? []).filter(k => !(s?.eventKeysSeen ?? []).includes(k));
    out.push(`- WS4 whitelist (read from \`server/events/validate.js\`): top \`${(w.top ?? []).join(', ')}\`; event \`${(w.event ?? []).join(', ')}\`; client \`SYNC_EVENT_FIELDS\` equals the server list: **${w.clientMatchesServer}**. Whitelisted keys not seen in this run: ${unseen.length ? `\`${unseen.join(', ')}\`` : 'none (all 12 were exercised)'}.`);
  }
  out.push(`- Photo diary: ${sc.photo?.length ?? 0} photo stored in the browser (${(sc.photo ?? []).map(p => `${p.size} bytes ${p.type}`).join('; ') || '-'}); ${s?.needlesSearched} fingerprint windows of its bytes (raw, hex, base64 at 3 alignments, percent-encoded) searched in every body and URL: **${(r.findings ?? []).some(f => f.code === 'photo-bytes') ? 'FOUND' : 'not found'}**.`);
  out.push(`- Service worker: active **${r.serviceWorkerActive}**; its own requests ${(r.requests ?? []).filter(q => q.target === 'service_worker').length}; answered ${(r.requests ?? []).filter(q => q.fromServiceWorker).length} page requests; static check of \`${(r.serviceWorkerStatic?.files ?? []).join(', ')}\` for upload-capable code (sendBeacon, XHR, WebSocket, POST, push/sync handlers): ${(r.serviceWorkerStatic?.uploadCapableCode ?? []).length ? `**${r.serviceWorkerStatic.uploadCapableCode.join(' ')}**` : 'none'}.`);
  out.push(`- Allowlist hosts not named in the page's Content-Security-Policy: ${(r.allowlistNotInCsp ?? []).length ? (r.allowlistNotInCsp ?? []).join(', ') : 'none'}.`);
  for (const f of (r.findings ?? [])) out.push(`- ${f.severity === 'fail' ? '**FINDING**' : 'Note'} \`${f.code}\`: ${f.message}${f.url ? ` (${f.url})` : ''}`);
  out.push('');
}
if (R.canary) {
  const c = R.canary;
  out.push('### Canary: the audit sees what it claims to see');
  out.push('');
  out.push(`The page itself was made to send what it must never send (a JPEG as a Blob, as base64 in JSON, in a multipart upload and in an XHR; a 21-point hand and a 468-point face mesh; an ImageBitmap; a beacon and a GET to an unknown host; a data: image in a query; an \`/api/events/sync\` call while sync is off). Verdict **${c.verdict}**: ${c.canaryExpected.length - c.canaryMissed.length} of ${c.canaryExpected.length} expected finding codes were raised${c.canaryMissed.length ? `; MISSED: ${c.canaryMissed.join(', ')}` : ''}.`);
  out.push('');
  out.push(`Codes raised: ${c.canaryCaught.map(x => `\`${x}\``).join(', ')}.`);
  out.push('');
}
const md = out.join('\n');
const start = '<!-- results:start -->'; const end = '<!-- results:end -->';
if (existsSync(reportFile)) {
  const cur = readFileSync(reportFile, 'utf8');
  if (cur.includes(start) && cur.includes(end)) {
    writeFileSync(reportFile, cur.slice(0, cur.indexOf(start) + start.length) + '\n' + md + '\n' + cur.slice(cur.indexOf(end)));
    console.log(`updated ${reportFile}`);
    process.exit(0);
  }
}
console.log(md);
