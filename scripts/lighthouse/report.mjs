#!/usr/bin/env node
// Writes the numbers of docs/agents/lighthouse-results/lighthouse.json into docs/agents/lighthouse-report.md between
// <!-- results:start --> and <!-- results:end -->, so no number in the report is typed by hand.
//   node scripts/lighthouse/report.mjs [--dir DIR] [--report FILE]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = fileURLToPath(new URL('../..', import.meta.url));
const argv = process.argv.slice(2);
const opt = (n, d) => { const i = argv.indexOf(n); return i === -1 ? d : argv[i + 1]; };
const dir = opt('--dir', join(REPO, 'docs', 'agents', 'lighthouse-results'));
const reportFile = opt('--report', join(REPO, 'docs', 'agents', 'lighthouse-report.md'));
const J = JSON.parse(readFileSync(join(dir, 'lighthouse.json'), 'utf8'));

const sec = (ms) => (ms / 1000).toFixed(1);
const out = [];
out.push(`_Generated by \`node scripts/lighthouse/report.mjs\` from \`docs/agents/lighthouse-results/lighthouse.json\`. Lighthouse ${J.lighthouse}, ${J.runs} runs per cell, the **median** is shown, ${J.at.slice(0, 16).replace('T', ' ')} UTC. Server flags: \`${J.flags}\`._`);
out.push('');
out.push('| Page | Device | Performance | SEO | Best practices | Accessibility | LCP | FCP | TBT | CLS | Failed SEO / best-practice audits |');
out.push('|---|---|---|---|---|---|---|---|---|---|---|');
for (const r of J.results) {
  const m = r.median;
  out.push(m
    ? `| \`${r.path}\` (${r.label}) | ${r.formFactor} | ${m.performance} | ${m.seo} | ${m.bestPractices} | ${m.accessibility} | ${sec(m.lcpMs)} s | ${sec(m.fcpMs)} s | ${m.tbtMs} ms | ${m.cls} | ${r.failedAudits.length ? r.failedAudits.map(a => `\`${a}\``).join(', ') : '-'} |`
    : `| \`${r.path}\` (${r.label}) | ${r.formFactor} | error | | | | | | | | ${r.runs.map(x => x.error).filter(Boolean)[0] ?? ''} |`);
}
out.push('');
out.push('Runs (performance score per run, to show the spread): ' + J.results.map(r => `\`${r.path}\` ${r.formFactor}: ${r.runs.map(x => x.error ? 'err' : x.performance).join('/')}`).join('; ') + '.');
out.push('');
out.push('### Installability (Chrome `Page.getInstallabilityErrors`; Lighthouse 13 has no PWA category)');
out.push('');
out.push('| `FEATURE_FLAGS` | Installability errors | Manifest errors | Manifest shortcuts | Manifest URL |');
out.push('|---|---|---|---|---|');
for (const i of J.installability) out.push(`| \`${i.flags}\` | ${i.error ? `error: ${i.error}` : (i.errors.length ? i.errors.map(e => e.errorId).join(', ') : 'none')} | ${(i.manifestErrors ?? []).length ? i.manifestErrors.join('; ') : 'none'} | ${i.shortcuts ?? '-'} | \`${i.manifestUrl ?? ''}\` |`);
const md = out.join('\n');
const cur = readFileSync(reportFile, 'utf8');
const start = '<!-- results:start -->'; const end = '<!-- results:end -->';
if (!cur.includes(start) || !cur.includes(end)) { console.log(md); process.exit(0); }
writeFileSync(reportFile, cur.slice(0, cur.indexOf(start) + start.length) + '\n' + md + '\n' + cur.slice(cur.indexOf(end)));
console.log(`updated ${reportFile}`);
